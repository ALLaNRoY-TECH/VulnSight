"""Markdown export of a scan report."""
from __future__ import annotations

from .engine import MODULE_LABELS

ICON = {"critical": "🟥", "high": "🟧", "medium": "🟨", "low": "🟦", "info": "⬜"}


def to_markdown(scan: dict) -> str:
    lines = [
        f"# VulnSight Security Report — {scan.get('host') or scan['target']}",
        "",
        f"- **Target:** `{scan['target']}`",
        f"- **Scan ID:** `{scan['id']}`",
        f"- **Started:** {scan['created_at']}",
        f"- **Duration:** {(scan.get('duration_ms') or 0) / 1000:.1f}s",
        f"- **Status:** {scan['status']}",
    ]
    if scan.get("score") is not None:
        lines.append(f"- **Security score:** {scan['score']}/100 (grade **{scan['grade']}**)")
    if scan.get("error"):
        lines.append(f"- **Error:** {scan['error']}")
    counts = scan.get("counts") or {}
    if counts:
        lines += ["", "| Severity | Issues |", "|---|---|"]
        lines += [f"| {ICON[k]} {k.title()} | {v} |" for k, v in counts.items()]

    issues = [f for f in scan.get("findings", []) if f["status"] in ("fail", "warn")]
    passed = [f for f in scan.get("findings", []) if f["status"] == "pass"]
    lines += ["", f"## Findings ({len(issues)})", ""]
    for i, f in enumerate(issues, 1):
        lines += [f"### {i}. {ICON[f['severity']]} [{f['severity'].upper()}] {f['title']}",
                  f"*Module: {MODULE_LABELS.get(f['module'], f['module'])}*", "", f["description"], ""]
        if f.get("evidence"):
            lines += ["**Evidence**", "```", f["evidence"], "```", ""]
        if f.get("remediation"):
            lines += [f"**Remediation:** {f['remediation']}", ""]
        if f.get("references"):
            lines += ["**References:** " + ", ".join(f["references"]), ""]
    lines += [f"## Passed checks ({len(passed)})", ""]
    lines += [f"- ✅ {f['title']}" for f in passed]
    lines += ["", "---", "_Generated by VulnSight — automated, non-intrusive assessment. "
              "Validate findings manually before acting._"]
    return "\n".join(lines)
